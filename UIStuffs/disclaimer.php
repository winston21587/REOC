  <script>
    (function () {
      const checkbox = document.getElementById('acceptCheckbox');
      const acceptBtn = document.getElementById('acceptBtn');
      const continueBtn = document.getElementById('continueBtn');
      const STORAGE_KEY = 'reoc_tos_accepted_v1';

      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'true') markAccepted(true);

      checkbox.addEventListener('change', () => {
        continueBtn.disabled = !checkbox.checked;
        updateUIForChecked(checkbox.checked);
      });

      acceptBtn.addEventListener('click', () => {
        checkbox.checked = true;
        continueBtn.disabled = false;
        updateUIForChecked(true);
        localStorage.setItem(STORAGE_KEY, 'true');
        acceptBtn.innerHTML = '<svg class="w-4 h-4" viewBox="0 0 24 24" fill="none"><path d="M5 13l4 4L19 7" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"/></svg> Accepted';
        acceptBtn.disabled = true;
      });

      continueBtn.addEventListener('click', () => {
        if (!checkbox.checked) return;
        document.querySelector('main').classList.add('opacity-0', 'pointer-events-none');
        const success = document.createElement('div');
        success.className = 'fixed inset-0 flex items-center justify-center p-6 bg-white';
        success.innerHTML = `
          <div class="max-w-md w-full rounded-2xl shadow-lg p-6 text-center border border-slate-100">
            <svg class="mx-auto w-12 h-12 text-red-600" viewBox="0 0 24 24" fill="none"><path d="M5 13l4 4L19 7" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"/></svg>
            <h3 class="mt-4 text-lg font-semibold text-red-700">Thank you</h3>
            <p class="mt-2 text-sm text-red-600">You have accepted the Terms of Service.</p>
            <div class="mt-4">
              <a href="#" class="inline-block bg-red-600 text-white py-2 px-4 rounded-lg shadow">Open Dashboard</a>
            </div>
          </div>
        `;
        document.body.appendChild(success);
      });

      function updateUIForChecked(checked) {
        if (checked) {
          continueBtn.classList.remove('border-red-300', 'text-red-600', 'bg-white');
          continueBtn.classList.add('bg-red-600', 'text-white');
        } else {
          continueBtn.classList.add('border-red-300', 'text-red-600', 'bg-white');
          continueBtn.classList.remove('bg-red-600', 'text-white');
        }
      }

      function markAccepted(flag) {
        checkbox.checked = flag;
        continueBtn.disabled = !flag;
        updateUIForChecked(flag);
        acceptBtn.disabled = flag;
        if (flag) {
          acceptBtn.innerHTML = '<svg class="w-4 h-4" viewBox="0 0 24 24" fill="none"><path d="M5 13l4 4L19 7" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"/></svg> Accepted';
        }
      }
    })();
